import { describe, expect, it } from 'vitest';
import { shortDateText } from '../lib/udhaarFormat.ts';
import { statementBlocks } from './creditPrint.ts';
import type { StatementFileMeta } from './statementFile.ts';

describe('customer statement print blocks', () => {
  it('uses a compact DD/MM/YY date', () => {
    expect(shortDateText('2026-11-13', 'Asia/Karachi')).toBe('13/11/26');
  });

  it('prints one signed amount per entry and the ending balance as total', () => {
    const meta = {
      shopName: 'Supreme Electronics',
      shopAddress: 'Hall Road, Lahore',
      shopPhone: '03001234567',
      customerName: 'Ali',
      phone: '03001234567',
      // Deliberately different from the last row: a date-filtered print must use the
      // statement's closing balance, not today's overall balance.
      balance: 999999,
      from: null,
      to: null,
      rows: [
        {
          date: '13 Nov 2026',
          dateShort: '13/11/26',
          description: 'Bill INV-1 (1 item)',
          descriptionShort: 'Bill INV-1',
          debit: 150000,
          credit: 0,
          balance: 150000,
          items: [
            {
              name: 'Galaxy A15',
              qtyMilli: 1000,
              unitPrice: 150000,
              amount: 150000,
            },
          ],
        },
        {
          date: '13 Nov 2026',
          dateShort: '13/11/26',
          description: 'Payment received - Cash',
          descriptionShort: 'Payment - Cash',
          debit: 0,
          credit: 25000,
          balance: 125000,
        },
      ],
      openingBalance: 0,
      lang: 'en',
      labels: {
        title: 'Statement',
        customer: 'Customer',
        phone: 'Phone',
        period: 'Statement period',
        periodValue: 'All time',
        date: 'Date',
        description: 'Description',
        debit: 'Debit',
        credit: 'Credit',
        balance: 'Balance',
        opening: 'Opening',
        total: 'Total',
        totalDebit: 'Total gave',
        totalCredit: 'Total got',
        closing: 'Closing balance',
        generatedBy: 'Generated by Bikri',
        asOf: 'As of 13 Nov 2026',
      },
    };
    const blocks = statementBlocks(meta);
    expect(blocks[0]).toEqual({ t: 'logo' });
    expect(blocks.at(-2)).toEqual({ t: 'feed', lines: 3 });
    expect(blocks.at(-1)).toEqual({ t: 'cut' });
    expect(blocks).toContainEqual({
      t: 'pair',
      left: '13/11/26 - Bill INV-1',
      right: '+Rs 1,500',
    });
    expect(blocks).toContainEqual({
      t: 'text',
      text: '  Galaxy A15 x1 @Rs1,500 =Rs1,500',
      size: 'small',
    });

    // On 58 mm, a long item name is truncated so its details stay on one line.
    const narrow = statementBlocks(
      {
        ...meta,
        rows: [
          {
            date: '13 Nov 2026',
            dateShort: '13/11/26',
            description: 'Bill INV-1 (1 item)',
            descriptionShort: 'Bill INV-1',
            debit: 5299000,
            credit: 0,
            balance: 5299000,
            items: [
              {
                name: 'Samsung Galaxy A15 128 GB',
                qtyMilli: 1000,
                unitPrice: 5299000,
                amount: 5299000,
              },
            ],
          },
        ],
      },
      32,
    );
    const itemLine = narrow.find(
      (block): block is { t: 'text'; text: string; size: 'small' } =>
        block.t === 'text' && block.text.includes('Samsung Galaxy'),
    );
    expect(itemLine?.text).toContain('...');
    expect(itemLine?.text.length ?? Infinity).toBeLessThanOrEqual(
      Math.floor((32 * 4) / 3),
    );
    expect(blocks).toContainEqual({
      t: 'pair',
      left: '13/11/26 - Payment - Cash',
      right: '-Rs 250',
    });
    expect(blocks).not.toContainEqual(
      expect.objectContaining({ t: 'pair', left: 'Debit' }),
    );
    expect(blocks).not.toContainEqual(
      expect.objectContaining({ t: 'pair', left: 'Credit' }),
    );
    expect(blocks).toContainEqual({
      t: 'pair',
      left: 'Balance',
      right: 'Rs 1,250',
      bold: true,
    });
    expect(blocks).toContainEqual({
      t: 'pair',
      left: 'Total',
      right: 'Rs 1,250',
      bold: true,
    });
  });
});

const labels = {
  title: 'KHATA STATEMENT',
  customer: 'Customer',
  phone: 'Phone',
  period: 'Statement period',
  periodValue: 'All time',
  date: 'Date',
  description: 'Description',
  debit: 'Debit',
  credit: 'Credit',
  balance: 'Balance',
  opening: 'Opening',
  total: 'Total',
  totalDebit: 'Total gave',
  totalCredit: 'Total got',
  closing: 'Closing balance',
  generatedBy: 'Generated by Bikri',
  asOf: 'As of 13 Nov 2026',
};

function statementMeta(
  overrides: Partial<StatementFileMeta> = {},
): StatementFileMeta {
  return {
    shopName: 'Supreme Electronics',
    shopAddress: 'Hall Road, Lahore',
    shopPhone: '03001234567',
    customerName: 'Ali',
    phone: '03001234567',
    balance: 0,
    from: null,
    to: null,
    rows: [],
    openingBalance: 0,
    lang: 'en',
    labels,
    ...overrides,
  };
}

describe('customer statement print details', () => {
  it('prints a negative balance with the ASCII receipt minus', () => {
    const blocks = statementBlocks(
      statementMeta({
        openingBalance: -200000,
        rows: [
          {
            date: '13 Nov 2026',
            description: 'Advance',
            debit: 0,
            credit: 0,
            balance: -250000,
          },
        ],
      }),
    );
    expect(blocks).toContainEqual({
      t: 'pair',
      left: 'Balance',
      right: '-Rs 2,500',
      bold: true,
    });
    expect(blocks).toContainEqual({
      t: 'pair',
      left: 'Opening',
      right: '-Rs 2,000',
      size: 'small',
    });
    // U+2212 triggers the per-line raster fallback; PC437 text mode needs `-`.
    expect(JSON.stringify(blocks)).not.toContain('\u2212');
  });

  it('honours the shop logo and shop-name receipt toggles', () => {
    const shown = statementBlocks(statementMeta());
    expect(shown[0]).toEqual({ t: 'logo' });
    expect(shown).toContainEqual({
      t: 'text',
      text: 'Supreme Electronics',
      align: 'center',
      bold: true,
    });
    const hidden = statementBlocks(
      statementMeta({ showLogo: false, showShopName: false }),
    );
    expect(hidden).not.toContainEqual({ t: 'logo' });
    expect(
      hidden.some(
        (block) => block.t === 'text' && block.text === 'Supreme Electronics',
      ),
    ).toBe(false);
  });

  it('truncates a product name by code points, not UTF-16 units', () => {
    const blocks = statementBlocks(
      statementMeta({
        rows: [
          {
            date: '13 Nov 2026',
            description: 'Bill',
            debit: 5000,
            credit: 0,
            balance: 5000,
            items: [
              {
                name: '😀'.repeat(40),
                qtyMilli: 1000,
                unitPrice: 5000,
                amount: 5000,
              },
            ],
          },
        ],
      }),
      32,
    );
    const line = blocks.find(
      (block) =>
        block.t === 'text' &&
        block.size === 'small' &&
        block.text.includes('😀'),
    );
    if (line?.t !== 'text') throw new Error('no item line');
    expect(line.text.isWellFormed()).toBe(true);
    expect(line.text).toContain('...');
    expect(line.text.length).toBeLessThanOrEqual(Math.floor((32 * 4) / 3));
  });
});
