#!/usr/bin/env node
// Generates packages/db/src/tables.ts (column lists per D1 table) from 0001_init.sql.
// Run after changing the migration: `node tools/gen-tables.mjs && pnpm exec biome format --write packages/db/src/tables.ts`.
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const SQL = readFileSync(
  join(ROOT, 'packages/db/migrations/0001_init.sql'),
  'utf8',
);
const OUT = join(ROOT, 'packages/db/src/tables.ts');

const tables = {};
for (const m of SQL.matchAll(/CREATE TABLE (\w+) \(([\s\S]*?)\n\) STRICT;/g)) {
  const cols = [];
  for (const line of m[2].split('\n')) {
    const c = /^\s*([a-z_][a-z0-9_]*)\s+(TEXT|INTEGER|REAL|BLOB)\b/.exec(line);
    if (c) cols.push(c[1]);
  }
  tables[m[1]] = cols;
}

const body = Object.entries(tables)
  .map(([t, cols]) => `  ${t}: [${cols.map((c) => `'${c}'`).join(', ')}],`)
  .join('\n');
const text = `// Generated by tools/gen-tables.mjs from packages/db/migrations/0001_init.sql. Do not edit.
/** Columns of every D1 table, in migration order. */
export const TABLE_COLUMNS = {
${body}
} as const satisfies Record<string, readonly string[]>;

export type D1Table = keyof typeof TABLE_COLUMNS;
`;
writeFileSync(OUT, text);
console.log(
  `wrote ${Object.keys(tables).length} tables (format with biome; apps/api/test/tables.test.ts checks it against D1)`,
);
